/* JSON is the editing source. Regenerate the static browser bundle after edits. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const languages = ['en', 'fr', 'es', 'pt', 'ar', 'de', 'it'];
const catalog = Object.fromEntries(languages.map(language => [language, JSON.parse(fs.readFileSync(path.join(root, 'locales', `${language}.json`), 'utf8'))]));
const keys = Object.keys(catalog.en).sort();
for (const [language, dictionary] of Object.entries(catalog)) {
  if (JSON.stringify(Object.keys(dictionary).sort()) !== JSON.stringify(keys)) throw new Error(`${language}: translation keys differ from English`);
  for (const [key, value] of Object.entries(dictionary)) {
    if (typeof value !== 'string' || !value.trim()) throw new Error(`${language}.${key}: empty or non-string translation`);
    const tokens = text => [...text.matchAll(/\{([a-zA-Z]+)\}/g)].map(match => match[1]).sort().join(',');
    if (tokens(value) !== tokens(catalog.en[key])) throw new Error(`${language}.${key}: placeholder mismatch`);
  }
}
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
for (const match of html.matchAll(/data-i18n-[a-z-]+="([^"]+)"/g)) {
  for (const key of match[1].split(' ')) {
    if (!Object.hasOwn(catalog.en, key)) throw new Error(`HTML references missing translation: ${key}`);
  }
}
fs.writeFileSync(path.join(root, 'assets', 'i18n-catalog.js'), '// Generated by node scripts/build-locales.cjs. Edit locales/*.json.\nwindow.ALIGNMENT_LOCALES = ' + JSON.stringify(catalog) + ';\n');
console.log(`Built ${languages.length} languages, ${keys.length} keys each.`);
